function translateValue(source, lang = getLocale()) {
  if (lang !== 'en') return englishToChinese.get(source) || source;
  if (messages[source]) return messages[source];
  for (const [pattern, formatter] of dynamicMessages) {
    const match = source.match(pattern);
    if (match) return formatter(...match);
  }
  return source;
}

const attributes = ['placeholder', 'title', 'aria-label', 'data-title'];
const originalText = new WeakMap();
const originalAttributes = new WeakMap();
const englishToChinese = new Map(Object.entries(messages).map(([zh, en]) => [en, zh]));
const englishPlaceholderToChinese = new Map(Object.entries(placeholders).map(([zh, en]) => [en, zh]));

function getLocale() {
  return localStorage.getItem('unigraph-language') === 'en' ? 'en' : 'zh';
}

function t(source, fallbackOrParams = source, params = undefined) {
  const fallback = typeof fallbackOrParams === 'string' ? fallbackOrParams : source;
  const interpolation = typeof fallbackOrParams === 'object' ? fallbackOrParams : params;
  if (i18n.global.te(source)) return i18n.global.t(source, interpolation || {});
  if (getLocale() !== 'en') return fallback;
  return translateValue(source, 'en') || fallback;
}

function translateTextNode(node, lang) {
  if (!originalText.has(node)) originalText.set(node, node.textContent);
  const source = originalText.get(node) || '';
  const key = source.trim();
  const translated = translateValue(key, lang);
  const next = source.replace(key, translated);
  if (node.textContent !== next) node.textContent = next;
}

function translateElement(element, lang) {
  if (['SCRIPT', 'STYLE', 'CODE', 'PRE'].includes(element.tagName)) return;
  const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    if (node.parentElement?.closest('script,style,code,pre')) return;
    if (node.textContent?.trim()) translateTextNode(node, lang);
  });
  if (!originalAttributes.has(element)) originalAttributes.set(element, {});
  const stored = originalAttributes.get(element);
  attributes.forEach((attribute) => {
    if (!element.hasAttribute(attribute)) return;
    if (stored[attribute] === undefined) stored[attribute] = element.getAttribute(attribute);
    const source = stored[attribute] || '';
    const translated = lang === 'en'
      ? (placeholders[source] || messages[source] || source)
      : (englishPlaceholderToChinese.get(source) || englishToChinese.get(source) || source);
    element.setAttribute(attribute, translated);
  });
}

function applyLanguage(lang = getLocale()) {
  const next = lang === 'en' ? 'en' : 'zh';
  setI18nLocale(next);
  document.documentElement.dataset.language = next;
  document.documentElement.lang = next === 'en' ? 'en' : 'zh-CN';
  const currentTitle = document.title.trim();
  const sourceTitle = englishToChinese.get(currentTitle) || currentTitle;
  document.title = translateValue(sourceTitle, next);
  if (document.body) translateElement(document.body, next);
  document.querySelectorAll('[data-lang-check]').forEach((icon) => {
    icon.style.visibility = icon.dataset.langCheck === next ? 'visible' : 'hidden';
  });
  window.dispatchEvent(new CustomEvent('unigraph:language-applied', { detail: { lang: next } }));
}

function setLocale(lang) {
  const next = lang === 'en' ? 'en' : 'zh';
  localStorage.setItem('unigraph-language', next);
  setI18nLocale(next);
  window.dispatchEvent(new CustomEvent('unigraph:language-change', { detail: { lang: next } }));
  applyLanguage(next);
}

let queued = false;
const observer = new MutationObserver(() => {
  if (queued) return;
  queued = true;
  requestAnimationFrame(() => {
    queued = false;
    applyLanguage();
  });
});

window.addEventListener('unigraph:language-change', (event) => applyLanguage(event.detail?.lang));
window.addEventListener('DOMContentLoaded', () => {
  applyLanguage();
  observer.observe(document.body, { childList: true, subtree: true });
});

